const RIGHT_ONLY = new Set([
  0x0622, 0x0627, 0x0629, 0x062f, 0x0630, 0x0631, 0x0632, 0x0698, 0x0648,
]);

function canConnect(cp: number, side: 'left' | 'right'): boolean {
  if (!FORMS[cp]) return false;
  if (RIGHT_ONLY.has(cp)) return side === 'right';
  return true;
}

function isLetter(cp: number): boolean {
  return cp in FORMS;
}

export function shapeArabic(input: string): string {
  const cps = [...input].map((ch) => ch.codePointAt(0) ?? 0);
  const out: number[] = [];
  for (let i = 0; i < cps.length; i += 1) {
    const cp = cps[i] ?? 0;
    const forms = FORMS[cp];
    if (!forms) {
      out.push(cp);
      continue;
    }
    let prev = i - 1;
    while (prev >= 0 && (cps[prev] === 0x0640 || cps[prev] === 0x200c)) prev -= 1;
    let next = i + 1;
    while (next < cps.length && (cps[next] === 0x0640 || cps[next] === 0x200d)) next += 1;
    const joinsPrev = prev >= 0 && isLetter(cps[prev] ?? 0) && canConnect(cps[prev] ?? 0, 'left');
    const joinsNext =
      next < cps.length && isLetter(cps[next] ?? 0) && canConnect(cp, 'left');
    const form = joinsPrev && joinsNext ? 3 : joinsNext ? 2 : joinsPrev ? 1 : 0;
    out.push(forms[form] ?? cp);
  }
  return String.fromCodePoint(...out);
}

const LTR_RE = /^[0-9A-Za-z۰-۹.,:%/+-]+$/;

function reverseGraphemes(s: string): string {
  return [...s].reverse().join('');
}

/** Visual order for an RTL line (Persian + Latin/digit islands). */
export function rtlVisual(input: string): string {
  const shaped = shapeArabic(input);
  const parts = shaped.split(/([0-9A-Za-z۰-۹.,:%/+-]+)/);
  const visual: string[] = [];
  for (let i = parts.length - 1; i >= 0; i -= 1) {
    const part = parts[i] ?? '';
    if (!part) continue;
    visual.push(LTR_RE.test(part) ? part : reverseGraphemes(part));
  }
  return visual.join('');
}
