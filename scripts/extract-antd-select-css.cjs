/**
 * One-off dev script: extracts antd's Select CSS (with the arianERP theme
 * tokens, un-hashed) into ui/primitives/selectCss.ts (lazy Select chunk). Run with the arianERP
 * checkout that has antd installed:
 *   node scripts/extract-antd-select-css.cjs C:/fallahi/newFront
 * antd is NOT a dependency of this package; this only reads its output.
 */
const fs = require('fs');
const path = require('path');
const { createRequire } = require('module');

const host = path.resolve(process.argv[2] || '.');
const req = createRequire(path.join(host, 'package.json'));
const React = req('react');
const { renderToString } = req('react-dom/server');
const { createCache, StyleProvider, extractStyle } = req('@ant-design/cssinjs');
const antd = req('antd');
const { ConfigProvider, Select } = antd;
const h = React.createElement;

const theme = {
  algorithm: antd.theme.defaultAlgorithm,
  hashed: false,
  token: {
    fontFamily: '',
    colorBgBase: '#fff',
    colorTextBase: '#000',
    colorBgContainer: '#fff',
    colorText: '#000',
  },
};

const opts = [{ value: 1, label: 'a' }, { value: 2, label: 'b' }];
function variants(direction) {
  const common = { options: opts, style: { width: 120 } };
  return h(
    ConfigProvider,
    { theme, direction, wave: { disabled: true } },
    h(Select, { ...common }),
    h(Select, { ...common, showSearch: true, allowClear: true, value: 1 }),
    h(Select, { ...common, disabled: true, value: 1 }),
    h(Select, { ...common, loading: true }),
    h(Select, { ...common, status: 'error' }),
    h(Select, { ...common, size: 'small' }),
    h(Select, { ...common, size: 'large' }),
    h(Select, { ...common, open: true, getPopupContainer: () => ({ appendChild() {} }) }),
    h(Select, { options: [], open: true }),
  );
}

let css = '';
for (const dir of ['ltr', 'rtl']) {
  const cache = createCache();
  renderToString(h(StyleProvider, { cache, hashPriority: 'low' }, variants(dir)));
  css += extractStyle(cache, true) + '\n';
}
// de-duplicate identical rule blocks across the two passes
const seen = new Set();
const out = css
  .split(/(?<=\})\s*(?=[^{}]+\{)/)
  .filter((r) => (seen.has(r.trim()) ? false : (seen.add(r.trim()), true)))
  .join('\n');

// ---- post-process: trim to what the single Select needs, tokenise colours, merge into erp-table.css
const TOKENS = {
  '#000': 'text', '#fff': 'bg', '#ffffff': 'bg', '#1677ff': 'primary', '#4096ff': 'primary-hover',
  '#d9d9d9': 'border', '#e6f4ff': 'primary-bg', '#faad14': 'warning', '#ffd666': 'warning-hover',
  '#ff4d4f': 'error', '#ff7875': 'error-hover',
};
const rules = [];
{
  let d = 0, s = 0;
  for (let i = 0; i < out.length; i++) {
    if (out[i] === '{') d++;
    else if (out[i] === '}' && --d === 0) { rules.push(out.slice(s, i + 1).trim()); s = i + 1; }
  }
}
const drop = /^(a[\s:\[{,]|\.data-ant|[^{]*ant-select-(compact|multiple|selection-overflow|borderless|underlined|filled|group)|[^{]*ant-select-selection-item-(remove|content))/;
const keep = /ant-select|ant-slide-(up|down)|ant-move-(up|down)|anticon|keyframes ant(Slide|Move)/;
const kept = [...new Set(rules.filter((r) => !drop.test(r) && (keep.test(r.split('{')[0]) || r.startsWith('@media'))))];
let body = kept.join('\n').replace(/;}/g, '}').replace(/#[0-9a-fA-F]{3,8}\b/g, (m) => {
  const t = TOKENS[m.toLowerCase()];
  if (!t) throw new Error('unmapped colour ' + m);
  return `var(--pdg-ant-${t})`;
});
body += '\n.anticon-spin{animation:pdgSpin 1s linear infinite}@keyframes pdgSpin{to{transform:rotate(360deg)}}';
// The stylesheet ships inside the lazy SelectImpl chunk, not in erp-table.css / the main bundle.
const tsFile = path.join(__dirname, '..', 'ui', 'primitives', 'selectCss.ts');
fs.writeFileSync(
  tsFile,
  '/* Generated by scripts/extract-antd-select-css.cjs - do not edit. */\n' +
    'export const ANT_SELECT_CSS = ' + JSON.stringify(body) + ';\n',
);
console.log('kept', kept.length, 'rules; wrote', tsFile);
